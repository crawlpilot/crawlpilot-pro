describe('block identification', () => {
    for (const [name, o, want] of BLOCKS) {
        it(`identifies ${name}`, () => {
            const c = classify(o);
            expect(c.errorClass).toBe(want.errorClass);
            expect(c.block).toMatchObject({ vendor: want.vendor, kind: want.kind, ...(want.confidence ? { confidence: want.confidence } : {}) });
            expect(c.protection).toContain(want.vendor);
            expect(c.blockSignal).toMatch(/^status \d+ \+ /);
        });
    }

    for (const [name, o, vendors] of ORDINARY) {
        it(`reads the ${name} as a page, and names its protection`, () => {
            const c = classify(o);
            expect(c.errorClass).toBe('none');
            expect(c.block).toBeUndefined();
            expect(c.protection ?? []).toEqual(vendors);
        });
    }

    it('puts generic block wording down to the site\'s one vendor', () => {
        const c = classify({ status: 200, cookies: ['_abck'], title: 'Access denied', text: 'Access denied.' });
        expect(c.block).toMatchObject({ vendor: 'Akamai', kind: 'block', confidence: 'low' });
    });

    it('a bare 403 on a protected site names the vendor, with low confidence', () => {
        expect(classify({ status: 403, headers: { server: 'cloudflare' }, text: longText }).block).toMatchObject({ vendor: 'Cloudflare', kind: 'block', confidence: 'low' });
    });

    it('two marks of one vendor make it sure', () => {
        const { finding } = identify({ status: 200, headers: {}, cookies: [], resources: [], navigation: [], title: 'Attention Required! | Cloudflare', text: 'Sorry, you have been blocked. Cloudflare Ray ID', suspicious: true });
        expect(finding).toMatchObject({ vendor: 'Cloudflare', kind: 'block', confidence: 'medium' });
        const two = identify({ status: 403, headers: {}, cookies: [], resources: [], navigation: [], title: 'Attention Required! | Cloudflare', text: 'Error 1020', suspicious: true });
        expect(two.finding).toMatchObject({ confidence: 'high', signals: ['Cloudflare error 1020/1010/1012', 'Cloudflare block page'] });
    });

    it('reads cookie names, never values', () => {
        expect(cookieNames('__cf_bm=SECRET; path=/\ndatadome=OTHER; Max-Age=1')).toEqual(['__cf_bm', 'datadome']);
    });

    it('has one signal name per vendor mark', () => {
        const keys = SIGNATURES.map(s => `${s.vendor}|${s.signal}`);
        expect(new Set(keys).size).toBe(keys.length);
    });
});
